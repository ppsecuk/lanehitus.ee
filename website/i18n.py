"""Render the shared website in Estonian and Russian without browser translation."""
from html import escape, unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re

from seo import render_metadata

LANGUAGES = {"et": "/", "ru": "/ru/"}
TEXT_ATTRIBUTES = {"alt", "aria-label", "aria-roledescription", "placeholder", "title"}
VOID_ELEMENTS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
CYRILLIC = re.compile(r"[А-Яа-яЁё]")


def load_catalog(path=None):
    path = path or Path(__file__).with_name("locales") / "et.json"
    return json.loads(Path(path).read_text())


class PageTranslator(HTMLParser):
    def __init__(self, language, catalog):
        super().__init__(convert_charrefs=True)
        self.language = language
        self.catalog = catalog
        self.parts = []
        self.stack = []

    def translate(self, value):
        if self.language == "ru" or not CYRILLIC.search(value):
            return value
        if value in self.catalog:
            return self.catalog[value]
        core = value.strip()
        if core in self.catalog:
            start = len(value) - len(value.lstrip())
            end = len(value.rstrip())
            return value[:start] + self.catalog[core] + value[end:]
        raise ValueError(f"Missing Estonian translation: {value!r}")

    def start_tag(self, tag, attrs, closed=False):
        metadata = dict(attrs)
        result = []
        for name, value in attrs:
            if tag == "html" and name == "lang":
                value = self.language
            elif value is not None and (name in TEXT_ATTRIBUTES or
                    tag == "meta" and metadata.get("name") == "description" and name == "content"):
                value = self.translate(value)
            elif name == "href" and "data-scroll-top" in metadata and value == "/":
                value = LANGUAGES[self.language]
            result.append(name if value is None else f'{name}="{escape(value, quote=True)}"')
        suffix = (" " + " ".join(result)) if result else ""
        self.parts.append(f"<{tag}{suffix}{' /' if closed else ''}>")
        if not closed and tag not in VOID_ELEMENTS:
            self.stack.append(tag)

    def handle_starttag(self, tag, attrs):
        self.start_tag(tag, attrs)

    def handle_startendtag(self, tag, attrs):
        self.start_tag(tag, attrs, closed=True)

    def handle_endtag(self, tag):
        self.parts.append(f"</{tag}>")
        if tag in self.stack:
            del self.stack[len(self.stack) - 1 - self.stack[::-1].index(tag):]

    def handle_data(self, data):
        if self.stack and self.stack[-1] in {"script", "style"}:
            self.parts.append(data)
        else:
            self.parts.append(escape(self.translate(data), quote=False))

    def handle_decl(self, decl):
        self.parts.append(f"<!{decl}>")

    def handle_comment(self, data):
        self.parts.append(f"<!--{data}-->")


def preserve_form_values(source):
    # Translated option labels must retain the enum values accepted by the server.
    return re.sub(
        r"<option\b(?![^>]*\bvalue\s*=)([^>]*)>([^<]*)</option>",
        lambda match: f'<option{match[1]} value="{escape(unescape(match[2]), quote=True)}">{match[2]}</option>',
        source,
    )


def render_page(source, language, catalog):
    if language not in LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")
    parser = PageTranslator(language, catalog["content"])
    parser.feed(preserve_form_values(source))
    parser.close()
    page = "".join(parser.parts)
    label = "Keele valik: eesti keel" if language == "et" else "Выбор языка: русский"
    options = "".join(
        f'<a href="{path}" data-language="{code}" lang="{code}"'
        + (' aria-current="page"' if code == language else "")
        + f'>{"Eesti" if code == "et" else "Русский"}</a>'
        for code, path in LANGUAGES.items()
    )
    picker = (f'<details class="language-picker"><summary aria-label="{label}">{language.upper()}</summary>'
              f'<div class="language-options">{options}</div></details>')
    page, count = re.subn(r'<details class="language-picker">.*?</details>', lambda _: picker, page, flags=re.S)
    if count != 1:
        raise ValueError("Expected exactly one language picker")
    title = unescape(re.search(r'<title>(.*?)</title>', page, re.S)[1])
    description = unescape(re.search(r'<meta name="description" content="([^"]*)">', page)[1])
    metadata = render_metadata(language, title, description)
    return page.replace("</head>", metadata + "</head>", 1)


def runtime_bundle(catalog):
    messages = {"et": {**catalog["content"], **catalog["runtime"]}}
    return "// Generated by website/build.py from website/locales/et.json.\nwindow.LAN_MESSAGES=" + json.dumps(messages, ensure_ascii=False, separators=(",", ":")) + ";\n"
